#!/usr/bin/env python3
"""
The facility's floor plan, in one place.

Two separate things need to agree about where a room is: the merged map that
BUILDS the building, and the desk console whose buttons are laid out as a map
of it. If those drift, the console stops being a map and becomes an arbitrary
arrangement of buttons -- so the coordinates live here, `build_merged_map.py`
takes its offsets from here rather than repeating them, and the Godot-side
plan drawing is GENERATED from the same data instead of transcribed.
"""
import os

# Room key -> (x, z) centre in metres. This IS the layout; nothing downstream
# is allowed a second opinion about it.
ROOM_XZ = {
    "Office": (0.0, 0.0),
    "WestHall": (-9.0, 0.0),
    "EastHall": (9.0, 0.0),
    "Storage": (-14.35, -13.5),
    "Archive": (14.35, -13.0),
    "Electrical": (0.0, -6.0),
    "Loading": (0.0, -19.5),
    "Arcade": (-11.0, 9.0),
    "DiningA": (0.0, 9.0),
    "DiningB": (11.0, 9.0),
}

# Camera id -> the room it watches.
CAM_ROOM = {
    "cam1": "WestHall", "cam2": "EastHall", "cam3": "Storage", "cam4": "Archive",
    "cam7": "Electrical", "cam8": "Loading",
    "cam9": "Arcade", "cam10": "DiningA", "cam11": "DiningB",
}
# Cameras watching a passage rather than a room, so they have no room centre.
CAM_POINT = {"cam5": (14.35, -9.5), "cam6": (-14.35, -9.5)}

CAMERAS = ["cam%d" % i for i in range(1, 12)]

# Breathing room around the outermost camera, so edge buttons do not sit on
# the panel's rim and the rooms behind them still read.
PLAN_PAD = 2.5


def cam_xz():
    """Camera id -> (x, z) in map metres."""
    out = {cam: ROOM_XZ[key] for cam, key in CAM_ROOM.items()}
    out.update(CAM_POINT)
    return out


def plan_bounds():
    """The rect the plan is normalised into: camera positions plus a margin.

    Deliberately NOT the building's full geometric extent. LOADING and STORAGE
    reach several metres further than their own cameras do, and normalising by
    that would squeeze the vertical camera spacing until neighbouring buttons
    touched -- CAM 4 and CAM 5 are only 3.5 m apart to begin with. The far
    corners of those rooms bleed off the edge of the plan instead, which is
    what a schematic on a control panel does anyway."""
    xs = [p[0] for p in cam_xz().values()]
    zs = [p[1] for p in cam_xz().values()]
    return (min(xs) - PLAN_PAD, max(xs) + PLAN_PAD,
            min(zs) - PLAN_PAD, max(zs) + PLAN_PAD)


def plan_uv(cam):
    """0..1 across the plan. v = 1 is NORTH (-Z) -- the top of the panel, and
    the direction the seated player is facing, so the map is heads-up."""
    x0, x1, z0, z1 = plan_bounds()
    x, z = cam_xz()[cam]
    return ((x - x0) / (x1 - x0), (z1 - z) / (z1 - z0))


def min_cam_spacing(width, height):
    """Closest pair of cameras once the plan is drawn `width` x `height`.

    The plan is stretched to fit whatever rect it is given, so u and v are not
    the same scale and a distance in normalised units would be meaningless.
    The console's button pitch is bounded by this number, so the builder
    reports it rather than discovering two fused caps in-engine."""
    uvs = {c: plan_uv(c) for c in cam_xz()}
    best = (1e9, None, None)
    keys = sorted(uvs)
    for i, a in enumerate(keys):
        for b in keys[i + 1:]:
            du = (uvs[a][0] - uvs[b][0]) * width
            dv = (uvs[a][1] - uvs[b][1]) * height
            d = (du * du + dv * dv) ** 0.5
            if d < best[0]:
                best = (d, a, b)
    return best


def write_gdscript(path, footprints, corridors):
    """Emit src/config/office_layout.gd from the map that was just built.

    `footprints` is the builder's own {key: ((x, z), W, D, H)} -- taken after
    the rooms are placed, so the quarter-turned halls report their WORLD size
    rather than their authored one. Generating this rather than hand-writing it
    is the point: the console draws the building that exists."""
    rooms = ",\n".join(
        '\t{"key": "%s", "x": %.3f, "z": %.3f, "w": %.3f, "d": %.3f}'
        % (key, off[0], off[1], w, d)
        for key, (off, w, d, _h) in sorted(footprints.items()))
    corrs = ",\n".join(
        '\t{"x0": %.3f, "z0": %.3f, "x1": %.3f, "z1": %.3f, "w": %.3f}'
        % (a[0], a[1], b[0], b[1], wid)
        for _name, a, b, _h, wid in corridors)
    cams = ",\n".join('\t"%s": Vector2(%.3f, %.3f)' % (c, p[0], p[1])
                      for c, p in sorted(cam_xz().items(),
                                         key=lambda kv: int(kv[0][3:])))
    x0, x1, z0, z1 = plan_bounds()
    body = f'''class_name OfficeLayout
extends RefCounted

## GENERATED by tools/office/office_layout.py -- do not edit by hand.
##
## The facility's floor plan in map metres, so the desk console can draw the
## building it is physically standing in. The 3D button caps are placed by the
## same generator from the same numbers, which is why a cap and its label
## cannot drift apart.
##
## Coordinates are the map's own: +X east, -Z north (the direction the seated
## player faces). BOUNDS is the rect the plan normalises into -- camera
## positions plus a margin, not the full building, so the far corners of
## LOADING and STORAGE bleed off the edge rather than crushing the spacing of
## every other button.

const ROOMS := [
{rooms},
]

const CORRIDORS := [
{corrs},
]

const CAMERA_XZ := {{
{cams},
}}

const BOUNDS := {{"x0": {x0:.3f}, "x1": {x1:.3f}, "z0": {z0:.3f}, "z1": {z1:.3f}}}


## Map metres -> 0..1 across the plan. y = 0 is NORTH, matching a texture's
## top-left origin, so this feeds straight into the panel's draw calls.
static func plan_uv(x: float, z: float) -> Vector2:
	return Vector2(
		(x - BOUNDS["x0"]) / (BOUNDS["x1"] - BOUNDS["x0"]),
		(z - BOUNDS["z0"]) / (BOUNDS["z1"] - BOUNDS["z0"]))
'''
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as fh:
        fh.write(body)
    return path
