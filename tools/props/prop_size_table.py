#!/usr/bin/env python3
"""Prop size table (docs/PROP_SIZES.md): every catalog prop's in-game size (as spawned, hunter scale included, from
tools/props/dump_prop_sizes.tscn) against its category's real-world range (data/scale/prop_size_ranges.json) at hunter
scale. Lists every prop, flags the out-of-range ones, and proposes the uniform rescale that brings each in range.

    python3 tools/props/prop_size_table.py /tmp/prop_sizes.json [before.json] > docs/PROP_SIZES.md
(with a second dump taken before a rescale, the table also lists every prop that changed, before -> after)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
RANGES = json.loads((ROOT / "data" / "scale" / "prop_size_ranges.json").read_text())
FACTOR = RANGES["hunter_factor"]


def category(prop_id):
    for cat in RANGES["categories"]:
        if any(w in prop_id for w in cat["words"]) and not any(w in prop_id for w in cat.get("not", [])):
            return cat
    return None


def dims(v):
    return {"height": v["y"], "long": max(v["x"], v["z"]), "short": min(v["x"], v["z"])}


def judge(prop_id, v):
    if prop_id in RANGES.get("keep_person_size", {}):
        return {"id": "kept", "exempt": "kept person-sized: " + RANGES["keep_person_size"][prop_id]}, "exempt", [], None
    cat = category(prop_id)
    if cat is None:
        return None, "uncategorised", [], None
    if "exempt" in cat:
        return cat, "exempt", [], None
    d = dims(v)
    out = []
    lo_f, hi_f = 0.0, 99.0
    for key in ("height", "long", "short"):
        if key not in cat:
            continue
        lo, hi = cat[key][0] * FACTOR, cat[key][1] * FACTOR
        if d[key] < lo - 0.005 or d[key] > hi + 0.005:
            out.append((key, d[key], lo, hi))
        lo_f = max(lo_f, lo / d[key])
        hi_f = min(hi_f, hi / d[key])
    if not out:
        return cat, "ok", [], None
    if lo_f > hi_f:
        return cat, "out", out, "no uniform scale fits: model change"
    target = FACTOR if lo_f <= FACTOR <= hi_f else round((lo_f + hi_f) / 2 / 0.05) * 0.05
    target = min(max(target, lo_f), hi_f)
    return cat, "out", out, round(target, 2)


def main():
    sizes = json.loads(pathlib.Path(sys.argv[1]).read_text())
    before = json.loads(pathlib.Path(sys.argv[2]).read_text()) if len(sys.argv) > 2 else {}
    rows = []
    for prop_id in sorted(sizes, key=str.lower):
        v = sizes[prop_id]
        cat, status, out, fix = judge(prop_id, v)
        rows.append((prop_id, v, cat, status, out, fix))
    counts = {}
    for r in rows:
        counts[r[3]] = counts.get(r[3], 0) + 1
    print("# Prop sizes (every catalog prop at hunter scale)\n")
    print("KT: \"do a size check for all props\". The world is built for a normal hunter (2.67 m; see")
    print("[SCALE_FIT.md](SCALE_FIT.md)), so a prop's real-world size is judged at %gx. Sizes are the spawned model's bounds" % FACTOR)
    print("(x by height by z, metres), with `PropModelCatalog.HUNTER_SCALE` applied. Ranges come from")
    print("`data/scale/prop_size_ranges.json` (person range x %g). **fix** is the extra uniform scale on top of the current one." % FACTOR)
    print("Generated by `tools/props/prop_size_table.py` from `tools/props/dump_prop_sizes.tscn`.\n")
    print("Summary: %s.\n" % ", ".join("%d %s" % (n, k) for k, n in sorted(counts.items())))
    changed = [p for p in sorted(before, key=str.lower) if p in sizes and abs(before[p]["y"] - sizes[p]["y"]) > 0.005]
    if changed:
        print("## Rescaled in this pass (%d)\n" % len(changed))
        print("| prop | category | before (x, h, z) | after (x, h, z) | scale |")
        print("| --- | --- | --- | --- | --- |")
        for prop_id in changed:
            b, a = before[prop_id], sizes[prop_id]
            cat = category(prop_id)
            print("| %s | %s | %.2f, %.2f, %.2f | %.2f, %.2f, %.2f | %.2f |" % (prop_id, cat["id"] if cat else "-",
                b["x"], b["y"], b["z"], a["x"], a["y"], a["z"], a["scale"]))
        print()
    print("## Out of range\n")
    print("| prop | category | size now (x, h, z) | scale now | out of range (wants) | fix |")
    print("| --- | --- | --- | --- | --- | --- |")
    for prop_id, v, cat, status, out, fix in rows:
        if status != "out":
            continue
        why = "; ".join("%s %.2f (%.2f-%.2f)" % (k, val, lo, hi) for k, val, lo, hi in out)
        fix_text = fix if isinstance(fix, str) else ("x%.2f" % fix)
        print("| %s | %s | %.2f, %.2f, %.2f | %.2f | %s | %s |" % (prop_id, cat["id"], v["x"], v["y"], v["z"], v["scale"], why, fix_text))
    print("\n## Uncategorised\n")
    un = [r for r in rows if r[3] == "uncategorised"]
    print(", ".join("`%s`" % r[0] for r in un) if un else "None.")
    print("\n## In range or exempt\n")
    print("| prop | category | size (x, h, z) | scale | status |")
    print("| --- | --- | --- | --- | --- |")
    for prop_id, v, cat, status, out, fix in rows:
        if status in ("ok", "exempt"):
            print("| %s | %s | %.2f, %.2f, %.2f | %.2f | %s |" % (prop_id, cat["id"], v["x"], v["y"], v["z"], v["scale"],
                status if status == "ok" else "exempt: " + cat["exempt"]))


if __name__ == "__main__":
    main()
